// ============================================================
//  模块名 : win_sample
//  作用   : 【取样地址发生器】—— 算出"这一行要从 SDRAM 的哪儿读、读多少个字"
//  层次   : 像素流水七级的第 ③ 级"取样"（B轨说明书 §2）
//  时钟域 : 像素域 40 MHz（它只算地址，真正的搬运交给 line_buf）
//  依据   : 契约第二节第 ②④ 条（每行字数 / 地址算法）、B轨说明书 §2、§6.1
// ------------------------------------------------------------
//  它和 line_buf 的分工（很重要，别混）：
//    · win_sample  只算数：这一行读哪个地址、读多少个字、这个像素在不在窗口里
//    · line_buf    只搬数：把算出来的那一行搬进行缓冲，并按时序交给显示
//    这么切的好处：地址算法能单独用 tb 穷举验，搬运的时序也能单独验。
//
//  ★ 一行是怎么变成"一次读请求"的：
//      屏幕第 N 行在显示时，本模块在行首（pix_x == 0）就把【第 N+1 行】
//      的起始字地址和字数算好、拍一下 line_go —— line_buf 收到就去搬。
//      搬一行只要 3~6 us，而一行要显示 26.4 us，所以永远来得及。
//
//  ★ 地址公式（1:1 不缩放，和契约第二节一致）：
//      源图第 v 行、第 u 列的字地址 = base + v * (src_w/2) + u/2
//    本模块要的是【行首 + 这一行读多少字】：
//      起始字地址 = base + v * words_per_line
//      读字数     = (窗口宽 + 1) / 2
//    ★ 一行两个像素装一个字，所以"读字数 = 像素数/2"。
//
//  ★ M1 只做 1:1（不放大缩小）。缩放是 M2 的 scaler_addr 的事，
//    那时候改的是"每个屏幕像素对应哪个源像素"，行首公式不变。
//
//  ★ 三个自动兜底（省得调用方到处判界）：
//    ① 窗口比源图【宽】→ 只读源图那么宽，超出部分不命中（显示底色）
//    ② 窗口比源图【高】→ 只认源图那么高，图下面那几行不命中（显示底色）
//       ★ 2026-09-26 补：原来只兜了"宽"，没兜"高" ——
//         症状是「图比窗口矮的时候，图下面那几行会显示上一帧的残留内容」
//         （因为不命中判断用的是窗口高，而行请求又发不出去，
//          于是行缓冲里那块旧数据被当成有效像素显示出来了）。
//         卡里图是 640x480、窗口开 800x600 时就会踩到这个。
//    ③ 下一行超出源图高 → 不发行请求
//    ④ 窗口还没开始 / 已经在下面 → 请求自动不发（行号算出来是回绕值，判界会挡住）
// ============================================================
`timescale 1ns / 1ps

module win_sample (
    input  wire        clk_pix,
    input  wire        rst_pix_n,

    // ---------------- 源图参数（来自描述符，契约第五节）----------------
    input  wire        src_valid,      // 描述符里的 valid：0 = 这个槽没装好
    input  wire [20:0] src_base,       // 槽基址（字地址）
    input  wire [11:0] src_w,          // 源图宽（像素）
    input  wire [11:0] src_h,          // 源图高（像素）

    // ---------------- 窗口矩形（屏幕坐标）----------------
    //   M1 由桩模块给（写死"全屏一个窗口"）；M2 换成 C 的窗口表
    input  wire        win_on,         // 窗口有效
    input  wire [11:0] win_x0,
    input  wire [11:0] win_y0,
    input  wire [11:0] win_w,          // 窗口宽（像素）
    input  wire [11:0] win_h,          // 窗口高（像素）

    // ---------------- 读口偏移补偿（2026-09-27，测试用旋钮）----------------
    //  ★ 上板实测：请求行首地址 B，读回来的数据却是从 B+3 开始的
    //    （8 个探针行全部恒定 +3 个字 = 6 像素）。这里把行首地址往前挪
    //    cmp_off 个字来抵消它。cmp_off 由 key1 现场调，用来量出那个偏移量；
    //    正式版应当把这个偏移在"读口那一层"彻底解决，而不是在这里补偿。
    input  wire [3:0]  cmp_off,

    // ---------------- 当前扫描位置（来自 video_timing）----------------
    input  wire [11:0] pix_x,
    input  wire [11:0] pix_y,
    input  wire        pix_de,         // 可见区

    // ---------------- 行请求（给 line_buf）----------------
    output reg         line_go,        // 一拍脉冲：请搬下面这一行
    output reg  [20:0] line_wbase,     // 起始【字】地址
    output reg  [11:0] line_words,     // 读多少个字（>=1）

    // ---------------- 给 line_buf 的读序号 + 命中 ----------------
    output wire [11:0] rd_index,       // 像素在窗口内的序号（0 起）
    output wire        hit             // 这一拍这个像素在窗口里（该显示源图）
);

    // ============================================================
    //  有效宽度：窗口比源图宽时，只认源图那么宽
    //  （M1 一般两者相等；留这一手是防止描述符和窗口表打架时读出越界）
    // ============================================================
    wire [11:0] eff_w = (win_w > src_w) ? src_w : win_w;
    wire [11:0] eff_h = (win_h > src_h) ? src_h : win_h;

    // 每行多少个字 = (有效宽 + 1) / 2  —— 奇数宽时行末空半个字（契约第 ② 条）
    wire [11:0] words_per_line = (eff_w + 12'd1) >> 1;

    // ============================================================
    //  命中判定：这一拍这个像素是不是落在窗口里
    // ============================================================
    wire in_x = (pix_x >= win_x0) && (pix_x < (win_x0 + eff_w));
    wire in_y = (pix_y >= win_y0) && (pix_y < (win_y0 + eff_h));

    assign hit      = pix_de && win_on && src_valid && in_x && in_y;
    assign rd_index = pix_x - win_x0;          // 窗口内序号（0 起）

    // ============================================================
    //  行首：算"下一行"的起始字地址，拍一下 line_go
    // ============================================================
    // 下一行对应的源图行号（1:1：显示行 - 窗口上边界）
    wire [11:0] next_row = pix_y + 12'd1 - win_y0;

    // 下一行还在窗口范围里、且没超过源图高度，才值得搬
    wire next_ok = win_on && src_valid
                && ((pix_y + 12'd1) >= win_y0)      // 下一行还没到窗口上方（防回绕）
                && (next_row < src_h);

    // ★ 乘法显式扩到 32 位再截：Verilog 里两个 12 位数相乘，结果宽度
    //   按"操作数宽度"算（12 位）会溢出 —— 这是最常见的坑之一。
    // ★★ 2026-09-28：A 现在按 BMP 的原始顺序（自下而上）往 SDRAM 里存，
    //    显示这边把行号翻过来读，屏上才是正的。
    //    ★ 这是"临时兜底"：正经做法是 A 在装载时就把行序翻好（A轨待改清单里记一条），
    //      之后这里应该恢复成直接用 next_row。
    wire [11:0] row_read = (src_h == 12'd0) ? 12'd0 : (src_h - 12'd1 - next_row);
    wire [31:0] row_off32 = {20'd0, row_read} * {20'd0, words_per_line};

    always @(posedge clk_pix or negedge rst_pix_n) begin
        if (!rst_pix_n) begin
            line_go    <= 1'b0;
            line_wbase <= 21'd0;
            line_words <= 12'd0;
        end
        else begin
            line_go <= 1'b0;                       // 默认不给脉冲

            if (pix_de && (pix_x == 12'd0) && next_ok) begin
                // ★ 减去读数偏移补偿（cmp_off = 0 时和原来完全一样）
                line_wbase <= src_base + row_off32[20:0] - {17'd0, cmp_off};
                line_words <= words_per_line;
                line_go    <= 1'b1;
            end
        end
    end

endmodule
