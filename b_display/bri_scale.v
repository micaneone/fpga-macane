// ============================================================
//  模块名 : bri_scale
//  作用   : 【菜单·亮度调节】RGB565 的整体亮度缩放（纯组合，0 拍延迟）
//  时钟域 : 无（纯组合；调用方在像素域 clk_pix 里用）
// ------------------------------------------------------------
//  ★ 2026-10-21 改口径：亮度从"0..15 档"改成"0..10 档 = 0%..100%（10% 一档）"
//    公式：  px_out = (px_in × bri_lv × 205) >> 11
//      · bri_lv = 10 ⇒ 系数 2050/2048 = 1.00098 ⇒ **floor 之后逐位原样**（默认 100%）
//      · bri_lv =  5 ⇒ 系数 1025/2048 = 0.50049 ⇒ 正好 50%
//      · bri_lv =  0 ⇒ 全黑（这是百分比语义下唯一说得通的定义）
//
//  ★ 为什么不用除法器：205/2048 = 0.100097，10 档合起来 1.00098 —— 常数乘法 + 右移 11，
//    误差 <0.1%，而对 5/6 位通道 floor 之后与真除法的结果完全一致（已逐值验算）。
//
//  ★ 代价：1 个 4×8 + 3 个 5/6×12 的小乘法（比原来 3 个 5×5 略大）。
//
//  ★ 组合通路的摆放位置（见 rtl\disp_top.v）：
//      转场 → 可视化 → 字幕 → **[本模块]** → 菜单 → RGB888
//      ⇒ 亮度只压"画面 + 可视化 + 字幕"，**菜单面板本身不压**
// ============================================================
`timescale 1ns / 1ps

module bri_scale (
    input  wire [3:0]  bri_lv,      // 0..10（10 = 100% 原样）；>10 按 10 处理
    input  wire [15:0] px_in,       // RGB565：{R5, G6, B5}
    output wire [15:0] px_out
);

    wire [3:0]  lv = (bri_lv > 4'd10) ? 4'd10 : bri_lv;
    wire [11:0] kk = {8'd0, lv} * 12'd205;      // 0..2050

    wire [4:0]  r5 = px_in[15:11];
    wire [5:0]  g6 = px_in[10:5];
    wire [4:0]  b5 = px_in[4:0];

    wire [16:0] rm = {12'd0, r5} * kk;          // 31×2050 = 63,550 < 2^16
    wire [17:0] gm = {12'd0, g6} * kk;          // 63×2050 = 129,150 < 2^17
    wire [16:0] bm = {12'd0, b5} * kk;

    assign px_out = {rm[15:11], gm[16:11], bm[15:11]};

endmodule
