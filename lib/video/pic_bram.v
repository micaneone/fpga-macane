// ============================================================
//  模块名 : pic_bram
//  作用   : 把一张小图存在片上 BRAM 里，按显示顺序读出来（5-4 用）
//  层次   : 显示链 第 3 层      时钟 → 时序 → 【内容】 → 输出
//  时钟域 : pixel_clk（本模块先只跑一个时钟，等段三接 SDRAM 才会出现真正的跨域）
//  原理   : 见 ../原理-显示链.md 第 6 节（同步 RAM 的读延迟、地址映射、缩放）
// ------------------------------------------------------------
//  这一版的目标不是"显示好看的图"，而是把这两件事跑通：
//      ① 写进去（谁写、什么时候写、写什么地址）
//      ② 按显示的节奏读出来（读地址由 x/y 算出来，而且要和 de 对齐）
//
//  建议的接口契约
//    input         clk        像素时钟
//    input         rst_n      复位，低有效
//    // 显示侧（读）
//    input         de         可见区
//    input  [11:0] x
//    input  [11:0] y
//    output [23:0] rgb        读出来的像素
//    // 写入侧（先做自测用；段三会换成 SD 卡送来的数据）
//    input         wr_en
//    input  [13:0] wr_addr
//    input  [23:0] wr_data
//
//  先算一遍容量（为什么要做"小"图）
//    160 x 120 x 24bit = 460,800 bit = 57.6 KB
//    640 x 480 x 24bit = 7,372,800 bit = 921.6 KB   ← BRAM 放不下，这才是要 SDRAM 的原因
//
//  验收标准（用"图案就是坐标"来自测，别用真照片）
//    · 先写死图案：比如每个像素的低 8 位 = x 的低 8 位 → 屏幕上是渐变竖条
//    · 竖条数量、方向能对上 → 说明读地址映射是对的
//    · 把地址公式里的 y 系数写错 → 竖条会变成斜纹，这种错一眼能看出来
//    · 小图在屏幕上的位置，取决于 x/y 怎么截位，自己算清楚再上板
// ------------------------------------------------------------
//  下面由你自己写。本文件故意是空的（只有注释），没有骨架。
// ============================================================
module pic_bram
(
    input         clk,
    input         rst_n,
    // 显示侧（读）
    input         de,
    input  [11:0] x,
    input  [11:0] y,
    output [23:0] rgb,
    // 写入侧（先做自测用；段三会换成 SD 卡送来的数据）
    input         wr_en,
    input  [13:0] wr_addr,
    input  [23:0] wr_data
);



   reg [26:0]cnt;
   always@(posedge clk)begin
        if(~rst_n)
            cnt<=8'b0;
        else cnt<=cnt+1;
   end
   wire [7:0]yy=y[7:0]+cnt[26-:8];
   wire [7:0]xx=x[7:0]+cnt[26-:8];
   assign rgb=de?{8'h00,yy[7:0],xx[7:0]}:24'h000000;
   
   
endmodule