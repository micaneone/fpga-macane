// ============================================================
//  模块名 : canvas_xform
//  作用   : 画布变换 —— 【本机屏幕像素 ↔ 全局画布坐标】（双机拼接用）
//             ① 正向：本机屏幕像素 (sx,sy) -> 全局画布坐标 (cx,cy)   ← 渲染用
//             ② 反向：全局画布坐标 (cx,cy) -> 本机屏幕像素 (sx,sy)   ← 鼠标用
//  层次   : 显示链 第 1 级（地址生成）的第 0 个模块
//  时钟域 : 像素域 40 MHz（正向路径寄存 1 拍；反向路径纯组合，给 C 用）
//  归属   : B（渲染侧）定义；C 的鼠标逆变换必须用【同一个 origin】
//  原理   : 总体规划 §2.6 / §2.8、common\artwork_def.v 第四节
// ------------------------------------------------------------
//  ★★ 2026-10-01：朝向（0/90/180/270）【已取消】—— 不再做竖屏。
//     需求变更 + 设计说明见 规划\B轨画布变换简化说明.md
//     （契约第四节随之改成"本机视口映射"，版本 v6 -> v7）。
//
//     现在这个模块只做一件事：**本机视口映射**
//       正向：cx = origin_x + sx          cy = origin_y + sy
//       反向：rx = cx - origin_x          ry = cy - origin_y
//             0 <= rx < SCR_W 且 0 <= ry < SCR_H 才算"落在本机视口里"
//
//     origin = 本机视口左上角在【画布】里的坐标，恒为非负：
//       单机            → 本机 (0,0)
//       对端在右        → 本机 (0,0)     对端 (800,0)
//       对端在左        → 本机 (800,0)   对端 (0,0)
//       对端在下        → 本机 (0,0)     对端 (0,600)
//       对端在上        → 本机 (0,600)   对端 (0,0)
//     （画布 (0,0) = 整个拼接范围的左上角；这条要和 C 说好，
//       因为 C 的鼠标逆变换直接吃它。）
//
//  为什么要有这个模块（总体规划 §2.6"最重要的架构建议"）：
//    从第一行渲染代码起就用"虚拟大画布坐标 + 本机视口偏移"来写，
//    单机时 origin = (0,0)、虚拟屏就是 800x600。加第二块板时只是
//    "改一个 origin 参数 + 接几根线 + 烧一份从机 bit"，渲染管线一行都不用重写。
//
//  ★ 正向和反向共用同一个 origin —— 这是"双机时鼠标不会推右走左"的唯一保证。
//    C 的鼠标逆变换【不要】另写一套：减 origin、判界、再钳制到画布范围。
//
//  延迟（流水线级数，B轨说明书 §6.2 要求每级注明）：
//    正向路径：px_* -> px_c*        1 拍
//              px_vld -> px_cx_vld  1 拍（★ 必须同拍，差一拍就整幅偏移）
//    反向路径：组合，0 拍
//
//  ★ 常量说明：本文件自带 localparam，不 `include artwork_def.v ——
//    这样它不依赖工具的 include 搜索路径，可以单独编译。
//    SCR_W / SCR_H 必须等于契约的 ART_SCR_W / ART_SCR_H，
//    跑偏了 tools\check_defs.py 会报（改一处务必改另一处）。
// ============================================================
`timescale 1ns / 1ps

module canvas_xform #(
    parameter integer SCR_W = 800,      // 每块屏的可见宽度
    parameter integer SCR_H = 600       // 每块屏的可见高度
)(
    input  wire        clk,
    input  wire        rst_n,

    // ---- 本机视口原点（在虚拟画布里的坐标；来自参数表，帧边界提交）----
    input  wire [12:0] origin_x,
    input  wire [12:0] origin_y,

    // ---- ① 正向（渲染用）：屏幕像素 -> 全局画布坐标，寄存 1 拍 ----
    input  wire [11:0] px_sx,
    input  wire [11:0] px_sy,
    input  wire        px_vld,
    output reg  [12:0] px_cx,
    output reg  [12:0] px_cy,
    output reg         px_cx_vld,       // px_vld 延迟 1 拍

    // ---- ② 反向（鼠标用）：全局画布坐标 -> 屏幕像素，组合输出 ----
    input  wire [12:0] ms_cx,
    input  wire [12:0] ms_cy,
    output wire [11:0] ms_sx,
    output wire [11:0] ms_sy,
    output wire        ms_inside        // 0 = 落点不在本机视口里
);

// ------------------------------------------------------------
//  正向：本机屏幕像素 -> 全局画布坐标（就是加本机视口原点）
// ------------------------------------------------------------
wire [12:0] fwd_cx = origin_x + {1'b0, px_sx};
wire [12:0] fwd_cy = origin_y + {1'b0, px_sy};

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        px_cx     <= 13'd0;
        px_cy     <= 13'd0;
        px_cx_vld <= 1'b0;
    end
    else begin
        px_cx     <= fwd_cx;
        px_cy     <= fwd_cy;
        px_cx_vld <= px_vld;       // ★ 必须和坐标一起打拍，否则差一拍就整体偏移
    end
end

// ------------------------------------------------------------
//  反向：全局画布坐标 -> 本机屏幕像素
//    1) 减掉本机视口原点（用有符号数，负的说明在视口之外）
//    2) 判界：落在 [0,SCR_W) x [0,SCR_H) 里才算在本机视口内
//  ★ 用 14 位有符号而不是 12 位：画布坐标可以到 8191，
//    先砍成 12 位（4095 上限）的话，origin 偏大时 inv_rx 会"回卷"，
//    判界跟着一起错 —— 宽度宁可多一位。
// ------------------------------------------------------------
wire signed [13:0] inv_dx = $signed({1'b0, ms_cx}) - $signed({1'b0, origin_x});
wire signed [13:0] inv_dy = $signed({1'b0, ms_cy}) - $signed({1'b0, origin_y});

wire inv_inside = (inv_dx >= 14'sd0) && (inv_dy >= 14'sd0)
               && (inv_dx < SCR_W)   && (inv_dy < SCR_H);

assign ms_inside = inv_inside;
assign ms_sx     = inv_inside ? inv_dx[11:0] : 12'd0;
assign ms_sy     = inv_inside ? inv_dy[11:0] : 12'd0;

// ------------------------------------------------------------
//  两屏位置对照表（把 origin 的含义钉死，避免"谁在 (0,0)"吵不清）
//  以左右拼接（画布 1600x600）为例：
//
//    布局              本机左上角(像素 0,0)在画布里的坐标 = origin
//    --------------   --------------------------------------
//    单机              (0, 0)
//    本机在左屏        (0, 0)      对端在右，画布 x = 800..1599
//    本机在右屏        (800, 0)    对端在左，画布 x = 0..799
//
//  上下拼接同理（画布 800x1200）：本机在上 (0,0)，本机在下 (0,600)。
//  判断依据：**看别人在哪边** —— 对端在左，本机就在 (800,0)。
// ------------------------------------------------------------

endmodule
