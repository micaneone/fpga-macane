// ============================================================
//  模块名 : color_bar
//  作用   : 彩条图案源 —— 只根据 x 决定颜色，8 条竖条
//  层次   : 显示链 第 3 层      时钟 → 时序 → 【内容】 → 输出
//  时钟域 : pixel_clk（和 video_timing 同一个域）
//  原理   : 见 ../原理-显示链.md 第 4 节
// ------------------------------------------------------------
//  建议的接口契约
//    input         clk     像素时钟
//    input         rst_n   复位，低有效
//    input         de      来自 video_timing，可见区为 1
//    input  [11:0] x       来自 video_timing
//    input  [11:0] y       来自 video_timing（彩条用不到，但接口留着，
//                          这样以后换成 pic_bram 时顶层不用改连线）
//    output [23:0] rgb     24 位像素，{R[7:0], G[7:0], B[7:0]}
//
//  为什么先做彩条：它不依赖任何存储器，把"时序对了"和"数据通了"两件事分开验。
//
//  验收标准
//    · 屏幕上 8 条等宽竖条，顺序：白 黄 青 绿 品红 红 蓝 黑
//    · 640 / 8 = 80，每条正好 80 个像素宽，边界干净
//    · 消隐期（de = 0）必须送黑色，不能送上一次的颜色
//    · 画面不滚动、不偏移、不抖
// ------------------------------------------------------------
//  下面由你自己写。本文件故意是空的（只有注释），没有骨架。
// ============================================================
module color_bar (
    input         clk,
    input         rst_n,
    input         de,
    input  [11:0] x,
    input  [11:0] y,
    output [23:0] rgb
);
localparam RGB={8'hFF,8'hFF,8'hFF,
                8'hFF,8'hFF,8'h00,
                8'h00,8'hFF,8'hFF,
                8'h00,8'hFF,8'h00,
                8'hFF,8'h00,8'hFF,
                8'hFF,8'h00,8'h00,
                8'h00,8'h00,8'hFF,
                8'h00,8'h00,8'h00};
assign rgb = de?RGB[191-24*(x/80)-:24]:24'h000000;

endmodule