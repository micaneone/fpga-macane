`timescale 1ns / 1ps

module zoom_sel_ref (
    input  wire        clk_pix,
    input  wire        rst_pix_n,

    input  wire [2:0]  level,       // 0=閫傞厤 1=1x 2=1.5x 3=2x 4=3x 5=4x
    input  wire [11:0] src_w,
    input  wire [11:0] src_h,
    input  wire [11:0] win_w,
    input  wire [11:0] win_h,

    output wire [31:0]        step_q16,
    output wire signed [31:0] off_u_q16,
    output wire signed [31:0] off_v_q16,
    output wire               bilin_en,

    // ---- 璇婃柇 ----
    output wire [31:0] step_fit_q16,   // 閫傞厤妗ｇ畻鍑烘潵鐨?step锛堜覆鍙?璋冭瘯鐪嬶級
    output wire        fit_busy        // 闄ゆ硶鍣ㄥ湪璺?
);

    // ============================================================
    //  妗ｄ綅琛紙鐢?宸ョ▼浠ｇ爜\tools\zoom_levels.py 鐢熸垚锛屽埆鎵嬫敼锛?
    //    step_q16 = round(65536 / Z)
    // ============================================================
    reg [31:0] step_tbl;
    always @(*) begin
        case (level)
            3'd1:    step_tbl = 32'h00010000;   // 1.0x
            3'd2:    step_tbl = 32'h0000AAAB;   // 1.5x
            3'd3:    step_tbl = 32'h00008000;   // 2.0x
            3'd4:    step_tbl = 32'h00005555;   // 3.0x
            3'd5:    step_tbl = 32'h00004000;   // 4.0x
            default: step_tbl = 32'h00010000;   // 閫傞厤妗ｇ敱 step_fit 瑕嗙洊
        endcase
    end

    // ============================================================
    //  "閫傞厤"妗ｏ細鍏堝喅瀹氬摢涓€杈规槸闄愬埗杞达紙浜ゅ弶鐩镐箻锛屼笉鍋氶櫎娉曪級
    //    win_w/src_w < win_h/src_h  <=>  win_w*src_h < win_h*src_w
    // ============================================================
    //   鈽?浜ゅ弶鐩镐箻鐨勪袱杈瑰埆鍐欏弽锛?
    //       瀹芥槸闄愬埗杞?<=> win_w/src_w < win_h/src_h <=> win_w*src_h < win_h*src_w
    wire [23:0] cmp_w   = win_w * src_h;
    wire [23:0] cmp_h   = win_h * src_w;
    wire        width_lim = (cmp_w < cmp_h);      // 瀹芥槸闄愬埗杞?
    wire        dims_ok = (src_w != 12'd0) && (src_h != 12'd0) &&
                          (win_w != 12'd0) && (win_h != 12'd0);

    // ============================================================
    //  鈽呪槄鈽?2026-10-17銆愬幓闈㈢Н 路 鏁村彧鍒犳帀闄ゆ硶鍣ㄣ€?
    //    "閫傞厤"妗ｈ绠? step = (num << 16) / den 锛?
    //    鑰?`win_w/win_h` 鍦ㄦ湰宸ョ▼閲屾槸**甯告暟**锛堥《灞傜獥鍙ｈ〃 `WIN_W(800)/WIN_H(600)`
    //    鈬?stub_win_table 鎶婂畠浠洿杩炴垚甯告暟鍙ｏ級鈬?杩欐槸**闄や互甯告暟**锛屼笉闇€瑕侀櫎娉曞櫒锛?
    //        q = (num << 16) / den 鈮?(num * K) >> 8 锛? K = round(2^24 / den)
    //          den = 800 鈬?K = 20972   锛?^24/800  = 20971.52锛?
    //          den = 600 鈬?K = 27962   锛?^24/600  = 27962.03锛?
    //    璇樊 鈮?num 脳 (0.5/2^24) 鈮?1e-4 LSB锛圦16.16 鐨?1 LSB = 1/65536 鍍忕礌锛夆噿 涓嶅彲瑙併€?
    //    浠ｄ环锛?2脳15 鐨勫父鏁颁箻锛堣惤 1 涓?DSP / 鍑犱釜绉讳綅鍔犳硶锛夛紱
    //    鏀剁泭锛歚udiv_q16_up`锛?76 LE锛夎繛鍚?div_start/need_fit/changed 閭ｄ竴鏁村
    //          鎻℃墜涓庡彉鍖栨娴嬩竴璧峰垹鎺夛紙瀹炴祴 u_zoom 471 鈫?绾?300 LE锛夈€?
    //    鈽?璇箟鍙樺寲锛氬師鏉ユ槸"闄ゆ硶鍣ㄧ畻瀹屽啀閿佸瓨锛坒it_busy 鏈熼棿 zoom_dual 涓嶉攣瀛橈級"锛?
    //      鐜板湪绾粍鍚堛€侀殢鏃舵湁鏁?鈬?`fit_busy` 鎭?0锛寊oom_dual 鐨?`!z_busy` 鎭掔湡銆?
    //    鈽?婧愬昂瀵搁潪娉曪紙0锛夋椂浠嶉€€鍥?Z=1 鐨勫畨鍏ㄥ€硷紝鍜屽師鏉?`step_fit` 澶嶄綅鍊煎悓鍙ｅ緞銆?
    // ============================================================
    localparam [14:0] K_DEN800 = 15'd20972;
    localparam [14:0] K_DEN600 = 15'd27962;

    wire [11:0] fit_num = width_lim ? src_w : src_h;
    wire [14:0] fit_k   = width_lim ? K_DEN800 : K_DEN600;
    wire [26:0] fit_prd = fit_num * fit_k;          // 12脳15 鈬?27 浣?
    wire [31:0] step_fit = dims_ok ? ({5'd0, fit_prd} >> 8) : 32'd65536;

    assign step_fit_q16 = step_fit;
    assign fit_busy     = 1'b0;

    // ============================================================
    //  杈撳嚭锛歴tep + 灞呬腑鍋忕Щ
    // ============================================================
    wire [31:0] step_calc = (level == 3'd0) ? step_fit : step_tbl;
    assign step_q16 = step_calc;

    // 鈽呪槄鈽?2026-10-03 涔樻硶鍣ㄧ槮韬紙鍜?scaler_addr 鍚屼竴濂楋紝涓哄洓绐楀彛鑵?DSP锛夛細
    //   鈽?`src_w * 65536` 鏄€愬父鏁颁箻銆戔啋 鍐欐垚宸︾Щ 16 浣嶏紝0 涓?DSP銆?
    //   鈽?win_w/win_h 鏀舵垚 10 浣嶏紙鈮?00锛夛紝step 鎹㈡垚銆怮4.12 绐勫畾鐐广€戯紙鍚?scaler_addr锛?
    //     鐞嗙敱瑙侀偅杈癸細TD 鐨勬垚鏈敱 32 浣嶉偅涓搷浣滄暟鎾戠潃锛屽彧鏈夋妸 step 鍘嬪埌 16 浣嶏紝
    //     涓€娆′箻娉曟墠钀借繘 1 涓?DSP锛決4.12 鐨勮寖鍥?绮惧害閮芥槸澶熺殑锛夈€?
    wire [15:0] zs12 = (step_calc[31:20] != 0) ? 16'hFFFF : step_calc[19:4];
    wire [25:0] wu26 = win_w[9:0] * zs12;    // 鈮?799脳65535 < 2^26锛圦4.12锛?
    wire [25:0] wv26 = win_h[9:0] * zs12;

    wire signed [31:0] wu = {2'd0, wu26, 4'b0000};   // Q4.12 鈫?Q16.16
    wire signed [31:0] wv = {2'd0, wv26, 4'b0000};
    wire signed [31:0] hu = $signed({20'd0, src_w}) <<< 16;   // = src_w * 65536
    wire signed [31:0] hv = $signed({20'd0, src_h}) <<< 16;

    assign off_u_q16 = (hu - wu) >>> 1;      // (src_w*65536 - win_w*step)/2
    assign off_v_q16 = (hv - wv) >>> 1;      // 绠楁湳鍙崇Щ锛氳礋鏁颁篃瀵?

    // Z >= 1锛堟斁澶ф垨 1:1锛夌敤鍙岀嚎鎬э紱Z < 1锛堢缉灏忥級鐢ㄦ渶杩戦偦
    assign bilin_en = (step_calc <= 32'd65536);

endmodule

