# ============================================================
#  flash.ps1 -- program the on-board SPI FLASH (power-cycle persistent)
#
#  WHY THIS SCRIPT EXISTS
#    tools\burn.ps1 only does an SRAM download: a power cycle restores
#    whatever is in FLASH.  For a demo/exhibition you want the current
#    bitstream IN FLASH so the board boots into it stand-alone.
#    Historically this was done by hand-editing flash_program_*.tcl in the
#    workspace root (8 near-identical copies).  This script replaces that:
#    one parameterised flow, logged, archivable, with a README reminder.
#
#  USAGE  (run from anywhere)
#    powershell -ExecutionPolicy Bypass -File .\tools\flash.ps1
#    ...  -Bit ..\burn\D5_opt_boot_20261025_121249.bit   (default: latest M2.bit)
#    ...  -Tag D5_opt_boot       label used in the log name     (default M2)
#    ...  -Speed 6 -Cable 0      bw_commands download options   (board defaults)
#    ...  -NoVerify              skip the read-back verification step
#    ...  -DryRun                print what would happen, program nothing
#
#  NOTES
#    - requires bw_commands_prompt.exe (not td_commands_prompt.exe)
#    - a full program pass is ~2 min and a verify pass ~10 s
#    - *** power must not be lost during PROGRAM (brick risk is low: the
#      board has a boot strap, but a half-written image will not boot) ***
#    - after flashing, power-cycle once and read the serial frame to prove
#      the FLASH image really booted (read_report.ps1 -Seconds 8)
#
#  *** KEEP THIS FILE PURE ASCII ***
# ============================================================

param(
    [string]$Project = '',
    [string]$BwExe   = 'D:\Anlogic\TD_6.2.1_Engineer_6.2.168.116\bin\bw_commands_prompt.exe',
    [string]$Bit     = '',
    [string]$Tag     = 'M2',
    [int]$Speed      = 6,
    [int]$Cable      = 0,
    [switch]$NoVerify,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($Project)) { $Project = Split-Path -Parent $PSScriptRoot }
$Project = (Resolve-Path -LiteralPath $Project).Path
$prj     = Join-Path $Project 'prj'

if ([string]::IsNullOrWhiteSpace($Bit)) { $Bit = Join-Path $prj 'M2_Runs\phy_1\M2.bit' }
if (-not (Test-Path -LiteralPath $Bit)) { throw ('bitstream not found: ' + $Bit + '  (build first: tools\build.ps1)') }
$Bit = (Resolve-Path -LiteralPath $Bit).Path
if (-not (Test-Path -LiteralPath $BwExe)) { throw ('bw_commands_prompt.exe not found: ' + $BwExe) }

$fi = Get-Item -LiteralPath $Bit
if ($fi.Length -lt 600000) { throw ('bitstream suspiciously small: ' + $fi.Length + ' bytes (' + $Bit + ')') }
Write-Host ('>>> bit     : ' + $Bit + '  ' + $fi.Length + ' bytes  ' + $fi.LastWriteTime) -ForegroundColor DarkGray
$age = (Get-Date) - $fi.LastWriteTime
if ($age.TotalMinutes -gt 60) {
    Write-Host ('>>> WARNING: bit is ' + [int]$age.TotalHours + ' h old; did you rebuild after the last RTL edit?') -ForegroundColor Yellow
}

# ---- tcl ------------------------------------------------------------------
$bitF = $Bit -replace '\\', '/'
$verifyBlock = @'
puts "=== VERIFY FLASH (verify_spi) ==="
set rcv [catch {download -bit $f -mode verify_spi -spd __SPD__ -cable __CAB__} rv]
puts "VERIFY rc=$rcv"
puts "VERIFY result: $rv"
'@
if ($NoVerify) { $verifyBlock = '# verify skipped (-NoVerify)' }
$tclTemplate = @'
# generated by tools/flash.ps1 -- do not edit by hand
set f {__BIT__}
puts "=== TARGET BIT: $f ==="
file stat $f st
puts "=== size: $st(size) bytes ==="
catch {get_flash_manufacturer} m
puts "=== PROGRAM FLASH (program_spi) ==="
set rc [catch {download -bit $f -mode program_spi -spd __SPD__ -cable __CAB__} r]
puts "PROGRAM rc=$rc"
puts "PROGRAM result: $r"
__VERIFY__
puts "=== DONE ==="
exit
'@

if ($DryRun) {
    Write-Host ''
    Write-Host '===== DRY RUN (FLASH untouched) =====' -ForegroundColor Cyan
    Write-Host ('  bit      : ' + $bitF)
    Write-Host ('  bw shell : ' + $BwExe)
    Write-Host ('  program  : download -bit <bit> -mode program_spi -spd ' + $Speed + ' -cable ' + $Cable)
    if (-not $NoVerify) { Write-Host ('  verify   : download -bit <bit> -mode verify_spi  -spd ' + $Speed + ' -cable ' + $Cable) }
    exit 0
}

$stamp   = Get-Date -Format 'yyyyMMdd_HHmmss'
$logs    = Join-Path $Project 'logs'
$runDir  = Join-Path $logs ('flash_' + $stamp)
$logPath = Join-Path $logs ('flash_' + $stamp + '.log')
New-Item -ItemType Directory -Force -Path $runDir | Out-Null

$tclText = $tclTemplate.Replace('__BIT__', $bitF).Replace('__SPD__', [string]$Speed).Replace('__CAB__', [string]$Cable).Replace('__VERIFY__', $verifyBlock.TrimEnd())
$tclPath = Join-Path $runDir 'flash.tcl'
[IO.File]::WriteAllText($tclPath, ($tclText + "`n"), (New-Object System.Text.UTF8Encoding($false)))

# ---- program --------------------------------------------------------------
$start = Get-Date
Write-Host '>>> programming FLASH (expect ~2 min; DO NOT cut power)...' -ForegroundColor Cyan
Push-Location $runDir
try {
    # same quirk as build/burn: TD's command line parser eats backslashes
    $tclArg = $tclPath -replace '\\', '/'
    $out = & $BwExe $tclArg *>&1
    $rc  = $LASTEXITCODE
} finally {
    Pop-Location
}
$text = ($out | Out-String)
[IO.File]::WriteAllText($logPath, $text, (New-Object System.Text.UTF8Encoding($false)))
$out | Out-Host

if ($text -notmatch 'PROGRAM rc=0') { throw ('"PROGRAM rc=0" not found -- FLASH program FAILED; see ' + $logPath) }
if (-not $NoVerify -and ($text -notmatch 'VERIFY rc=0')) {
    throw ('"VERIFY rc=0" not found -- FLASH read-back mismatched; see ' + $logPath)
}

Write-Host ''
Write-Host ('===== FLASH OK ===== ' + [int]((Get-Date) - $start).TotalSeconds + ' s') -ForegroundColor Green
Write-Host ('  bitstream : ' + $Bit)
Write-Host ('  log       : ' + $logPath)
Write-Host '  next      : power-cycle the board once, then run:'
Write-Host ('              powershell -ExecutionPolicy Bypass -File ' + (Join-Path $Project 'read_report.ps1') + ' -Seconds 8 -Port COM6')
exit 0
