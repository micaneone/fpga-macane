// ============================================================
//  模块名 : bri_scale
//  作用   : 【菜单·亮度调节】RGB565 的整体亮度缩放（纯组合，0 拍延迟）
//  时钟域 : 无（纯组合；调用方在像素域 clk_pix 里用）
// ------------------------------------------------------------
//  公式：  px_out = (px_in × (bri_lv + 1)) >> 4
//     · bri_lv = 15 ⇒ 系数 16 ⇒ (c×16)>>4 = c **逐位原样**（默认档，不改变任何画面）
//     · bri_lv =  0 ⇒ 系数  1 ⇒ 每个通道 ≈ c/16（接近全黑，但不是 0）
//     · 16 档单调不减（floor(c×k/16) 对 k 单调）
//
//  ★ 为什么不用「右移 + 减」那种土办法：
//      用 c - (c>>4)×dim 的写法，5 位通道里 c<16 的像素永远躲不掉
//      （c>>4 = 0 ⇒ 完全不变）⇒ 暗部一点都不变暗，最低档也只压到 ~50%。
//      这里用真乘法，能一路压到接近黑，而且 bri_lv=15 时**数学上恒等**，
//      用户可以"不动它就完全不影响画面"。
//
//  ★ 代价：3 个小乘法（5×5 / 6×5 / 5×5）。位宽全部算过，不会溢出：
//      R: 31×16 = 496 < 2^10      G: 63×16 = 1008 < 2^11      B: 31×16 = 496
//      取 [8:4] / [9:4] / [8:4] 之后正好回到 5/6/5 位。
//    ★ 因为乘的是**变量**（不是常数），TD 会用宏乘法器/移位加法；宽度这么小，
//      实测见交接文档 §⑩（面积/时序都在预算内）。
//
//  ★ 组合通路的摆放位置（见 rtl\disp_top.v）：
//      转场 → 可视化 → 字幕 → **[本模块]** → 菜单 → RGB888
//      ⇒ 亮度只压"画面 + 可视化 + 字幕"，**菜单面板本身不压**
//        （否则亮度调到很低时菜单自己也看不清，就没法把它调回来了）。
// ============================================================
`timescale 1ns / 1ps

module bri_scale (
    input  wire [3:0]  bri_lv,      // 0..15（15 = 原样，0 = 最暗）
    input  wire [15:0] px_in,       // RGB565：{R5, G6, B5}
    output wire [15:0] px_out
);

    wire [4:0]  k5 = bri_lv + 5'd1;             // 系数 1..16

    wire [4:0]  r5 = px_in[15:11];
    wire [5:0]  g6 = px_in[10:5];
    wire [4:0]  b5 = px_in[4:0];

    // ★ 显式把两个操作数都补到乘积位宽再乘：不依赖"上下文定宽"的隐式规则，
    //   ModelSim 与 TD 逐位一致（`sim\tb_bri_scale.v` 对 17×65536 种组合穷举过）。
    wire [9:0]  rm = {5'd0, r5} * {5'd0, k5};   // 5×5 ⇒ 低 10 位足够
    wire [10:0] gm = {5'd0, g6} * {5'd0, k5};   // 6×5 ⇒ 低 11 位足够
    wire [9:0]  bm = {5'd0, b5} * {5'd0, k5};

    assign px_out = {rm[8:4], gm[9:4], bm[8:4]};

endmodule
