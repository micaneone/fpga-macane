// ============================================================
//  模块名 : bilinear
//  作用   : 双线性插值 —— 放大时把 4 个相邻源像素按权重混合成一个屏幕像素
//  层次   : 像素流水第 ③ 级"取样"之后的插值（放大档才用；缩小档权重=0 退化成抽点）
//  时钟域 : 像素域 40 MHz（纯组合）
//  依据   : 规划\B轨缩放器设计说明.md §6
// ------------------------------------------------------------
//  算法（3 次线性插值，可分离）：
//      top = p00 + fu·(p01 − p00)      // 上面一行横向插值
//      bot = p10 + fu·(p11 − p10)      // 下面一行横向插值
//      out = top + fv·(bot − top)      // 纵向插值
//    ★ 先横后纵，只要 3 次插值（不是 4 个权重乘积 + 4 次求和）。
//
//  权重约定：fu/fv ∈ [0,255]，分母 256（fu=255 表示"几乎到邻居"）。
//  所以我们插值时用的是 >>8 —— 这也是 ±1 取整误差的来源，符合设计允许。
//
//  ★ 颜色域：先把 RGB565 展开成每通道 8 位（低位补高位），插值、钳制，
//    最后再截回 RGB565（取高 5/6/5 位）。若直接对打包的 565 做加减，
//    通道之间会互相借位 —— 这是最常见的写法错误。
//
//  ★ 乘法器数量：每通道 3 次插值 x 3 个通道 = 9 个小乘法器。
//    （设计说明里低估成"3 个"；EG4S20 有 29 个 DSP，见实施计划 §资源。）
// ============================================================
`timescale 1ns / 1ps

module bilinear (
    input  wire [15:0] p00,     // (u,   v  )
    input  wire [15:0] p01,     // (u+1, v  )
    input  wire [15:0] p10,     // (u,   v+1)
    input  wire [15:0] p11,     // (u+1, v+1)
    input  wire [7:0]  fu,      // 列权重 0..255
    input  wire [7:0]  fv,      // 行权重 0..255
    output wire [15:0] pix
);

    // ============================================================
    //  RGB565 -> 每通道 8 位（低位补高位）
    // ============================================================
    function [7:0] ex_r; input [15:0] p; begin ex_r = {p[15:11], p[13:11]}; end endfunction
    function [7:0] ex_g; input [15:0] p; begin ex_g = {p[10:5],  p[6:5]};  end endfunction
    function [7:0] ex_b; input [15:0] p; begin ex_b = {p[4:0],   p[2:0]};  end endfunction

    // ============================================================
    //  一次线性插值（8 位域）：a + (b−a)·w/256，结果钳到 [0,255]
    // ============================================================
    function [7:0] lerp8;
        input [7:0] a;
        input [7:0] b;
        input [7:0] w;
        reg signed [9:0]  d;      // b − a，范围 −255..255
        reg signed [17:0] prod;   // d·w，|≤ 65025|
        reg signed [10:0] r;
        begin
            d    = $signed({2'b00, b}) - $signed({2'b00, a});
            prod = d * $signed({1'b0, w});
            r    = $signed({3'b000, a}) + (prod >>> 8);   // 算术右移：负数也对
            if (r[10])             r = 11'sd0;            // 负数 -> 0
            else if (r > 11'sd255) r = 11'sd255;          // 超 255 也钳
            lerp8 = r[7:0];
        end
    endfunction

    // ---- 横向：上下两行各自插值 ----
    wire [7:0] r0 = lerp8(ex_r(p00), ex_r(p01), fu);
    wire [7:0] g0 = lerp8(ex_g(p00), ex_g(p01), fu);
    wire [7:0] b0 = lerp8(ex_b(p00), ex_b(p01), fu);
    wire [7:0] r1 = lerp8(ex_r(p10), ex_r(p11), fu);
    wire [7:0] g1 = lerp8(ex_g(p10), ex_g(p11), fu);
    wire [7:0] b1 = lerp8(ex_b(p10), ex_b(p11), fu);

    // ---- 纵向 ----
    wire [7:0] rr = lerp8(r0, r1, fv);
    wire [7:0] gg = lerp8(g0, g1, fv);
    wire [7:0] bb = lerp8(b0, b1, fv);

    // ---- 截回 RGB565 ----
    assign pix = {rr[7:3], gg[7:2], bb[7:3]};

endmodule
