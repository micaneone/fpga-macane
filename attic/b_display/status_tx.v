// ============================================================
//  模块名 : status_tx
//  作用   : B -> A 的【状态回推】—— 告诉 A "哪几个槽现在可以覆盖"
//  层次   : 显示链最底层（B 轨）；和 desc_rx 正好是反方向的一对
//  时钟域 : 两个 —— B 侧（写）在【像素域 40 MHz】，A 侧（读）在【控制域 50 MHz】
//  依据   : A轨说明书 §4.6（槽位状态机）、§5.3；契约文件第五节"B -> A 状态回推"
// ------------------------------------------------------------
//  为什么必须有它（这是规划里漏掉的一条）：
//    A轨说明书 §4.6 给 A 画了一张槽位状态机，里面写着
//        "转场期间旧槽还在被读，不能提前复用来装下一张"
//    可是"转场结束了没有"【只有 B 知道】—— B 自己用 frame_id 算转场进度。
//    A 的接口表里原来一根 B->A 的线都没有，所以这一条 A 根本没法实现。
//    这个模块就把这句话变成一根实实在在的信号。
//
//  它搬的东西（状态字，16 位，定义见 artwork_def.v 第五节）：
//      a_status[11:0]  slot_free —— 每槽 1 位，★ 1 = 现在没在被读，A 可以覆盖
//                                     0 = 别动它（正在显示 / 正在转场）
//                                   现在只用到低 2 位（2 个大槽）；
//                                   ★ 小槽一加，槽数会变多，但**这一段宽度不用改**
//                                     （契约里 STAT_SLOT_W = 12，够放
//                                       "2 个大槽 + 10 个小槽"）
//      a_status[15:12] 保留，现在恒为 0
//
//  ★ 为什么"槽空"这件事只能由 B 说：
//      A 知道自己往哪些槽写过，但不知道【B 当前在显示哪个槽】（那是窗口表
//      决定的，C 随时可能改），更不知道转场期间 B 同时在读两个槽。
//      所以由 B 出这个信号，A 只管等绿灯 —— 谁手里有真相谁发信号。
//
//  ★ 用法（A 那边）：
//      想往槽 k 写之前，看 a_status[k]：
//        1 = 可以写（写完整张图之后，再翻描述符的 valid 才算交付）
//        0 = 等下一帧再看（每帧都会刷新）
//      ★ 顺序不能反：**先写满、再提交**。B 只有在 A 提交描述符之后
//        才会去读那个槽，所以"A 写完才提交"这一条天然保证了不会撞车，
//        本模块不需要回执（不需要像 desc_rx 那样等 ack）。
//
//  ★ 为什么复位后发的是 0（全忙）而不是"全空"：
//     保守。B 还没起来的时候，A 如果以为"全空、随便写"，有可能正好
//     覆盖掉 B 已经在用的槽。反过来只是让 A 多等一帧（16 ms），
//     代价可以忽略。
//
//  ★ 什么时候发：只在【帧边界】看一次值，而且**只在值变了才发**。
//      槽的可用性一帧一变就够了（A 是秒级的装载速度），
//      每帧都发的话跨域次数白白多 60 倍，还得让 A 每帧都去读。
//
//  ★ 提醒（这一条要写进 M1 的验收清单）：
//      本模块**不做任何"什么是忙"的判断**，它只是个搬运工 ——
//      slot_free 由合成器算好送进来（"当前前台表用到的槽" + "转场中的槽"
//      取反）。M1 还没有合成器的时候，直接把 slot_free 接成全 1
//      （等于"随便写"）就能先让 A 跑起来。
// ============================================================
`timescale 1ns / 1ps

module status_tx #(
    parameter integer SLOT_NUM = 2        // 槽位数（= 契约的 SDR_SLOT_NUM，现在 = 2 个大槽）
                                          //  ★ 必须 <= 契约的 STAT_SLOT_W(12)，
                                          //    check_defs.py 会盯着
)(
    // ---------------- B 侧：像素域 40 MHz ----------------
    input  wire        clk_pix,
    input  wire        rst_pix_n,
    input  wire        frame_start,               // 每帧一次脉冲（B 自己产生）
    input  wire [SLOT_NUM-1:0] slot_free,         // 合成器算好：1 = 没在被读

    // ---------------- A 侧：控制域 50 MHz ----------------
    input  wire        clk_ctl,
    input  wire        rst_ctl_n,
    output reg  [15:0] a_status,                  // 最近一版状态字（值总是完整的）
    output reg         a_status_tgl,              // 每收到一版翻一次（诊断用）
    output reg  [15:0] o_version                  // 收到过几版（诊断用）
);

    // ------------------------------------------------------------
    //  位段（与 common\artwork_def.v 第五节"B -> A 状态回推"一致）
    //     [4:0] slot_free   [15:5] 保留(0)
    // ------------------------------------------------------------
    localparam integer S_SLOT_FREE = 0;

    // ============================================================
    //  B 侧 40 MHz：帧边界看一眼，值变了才发
    // ============================================================
    reg [SLOT_NUM-1:0] sf_shadow;     // 上一次发出去的值（用来比"变没变"）
    reg [15:0]         st_pay;        // 要发出去的那一份（只在翻 toggle 时变）
    reg                st_tgl;        // 翻一次 = 有新值，跨域的那根线

    always @(posedge clk_pix or negedge rst_pix_n) begin
        if (!rst_pix_n) begin
            sf_shadow <= {SLOT_NUM{1'b0}};    // 和 st_pay 的复位值(0)对齐
            st_pay    <= 16'd0;
            st_tgl    <= 1'b0;
        end
        else if (frame_start && (slot_free !== sf_shadow)) begin
            // ★ 先改数据、同拍翻 toggle：A 侧看到 toggle 变的时候，
            //   已经比这里晚 2~3 个 50MHz 周期（≥40 ns），数据早就稳了。
            //   这就是契约第三节那条"数据先稳定 + toggle"的规矩。
            sf_shadow <= slot_free;
            st_pay    <= slot_free;          // 高位自动补 0（保留位）
            st_tgl    <= ~st_tgl;
        end
    end

    // ============================================================
    //  A 侧 50 MHz：接住 toggle，把那一份整体采下来
    // ============================================================
    reg [2:0] cs;                        // 三级同步
    wire      st_edge = cs[1] ^ cs[2];

    always @(posedge clk_ctl or negedge rst_ctl_n) begin
        if (!rst_ctl_n) begin
            cs           <= 3'd0;
            a_status     <= 16'd0;       // 复位后：全忙（见文件头）
            a_status_tgl <= 1'b0;
            o_version    <= 16'd0;
        end
        else begin
            cs <= {cs[1:0], st_tgl};
            if (st_edge) begin
                a_status     <= st_pay;              // 此时它已经稳了
                a_status_tgl <= ~a_status_tgl;
                o_version    <= o_version + 16'd1;
            end
        end
    end

endmodule
